// Arabic interface copy. Medical abbreviations, scoring systems and product names (CT, MRI,
// LI-RADS, AWS Quick, Word, Pro) stay in Latin script, as Arabic-speaking radiologists write them.

const rules = new Intl.PluralRules('ar');

/** Arabic counted nouns change form with the number: 0 · 1 · 2 · 3–10 · 11–99 · 100+. */
function count(
  n: number,
  forms: { zero: string; one: string; two: string; few: string; many: string; other: string },
): string {
  return forms[rules.select(n) as keyof typeof forms].replace('{n}', String(n));
}

