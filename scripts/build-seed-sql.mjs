#!/usr/bin/env node
// Turns the extracted legacy catalog into idempotent seed SQL (categories + apps).
//
// Usage: node scripts/build-seed-sql.mjs <legacy-extract/catalog.json> > supabase/seed.sql

import fs from 'node:fs';
import { toRows } from './lib/catalog-rows.mjs';

const [catalogPath] = process.argv.slice(2);
if (!catalogPath) {
  console.error('usage: build-seed-sql.mjs <catalog.json>');
  process.exit(1);
}

const { categoryRows, appRows } = toRows(JSON.parse(fs.readFileSync(catalogPath, 'utf8')));

const q = (v) =>
  v === null || v === undefined
    ? 'null'
    : typeof v === 'number'
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;

function insert(table, rows, conflictKey) {
  const cols = Object.keys(rows[0]);
  const updates = cols
    .filter((c) => c !== conflictKey && c !== 'tier')
    .map((c) => `${c} = excluded.${c}`)
    .join(', ');
  return [
    `insert into public.${table} (${cols.join(', ')}) values`,
    rows.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n'),
    // `tier` is only set on first insert so re-seeding never undoes an admin's choice.
    `on conflict (${conflictKey}) do update set ${updates};`,
  ].join('\n');
}

process.stdout.write(
  [
    '-- Generated by scripts/build-seed-sql.mjs from the legacy offline suite. Idempotent.',
    'begin;',
    '',
    insert('categories', categoryRows, 'name'),
    '',
    insert('apps', appRows, 'id'),
    '',
    'commit;',
    '',
  ].join('\n'),
);
